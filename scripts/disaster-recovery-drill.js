#!/usr/bin/env node

const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const DEFAULT_FIXTURE = "tests/fixtures/server-backups/agora-workspace-backup-demo.json";
const COUNT_KEYS = ["companies", "projects", "tasks", "users", "memberships", "auditEvents"];

if (require.main === module) {
  const args = parseArgs(process.argv.slice(2));
  const report = runDisasterRecoveryDrill(args);

  if (args.json) {
    console.log(JSON.stringify(report, null, 2));
  } else {
    printReport(report);
  }

  if (!report.ok) {
    process.exitCode = 1;
  }
}

function parseArgs(values) {
  return values.reduce((result, value) => {
    if (result.pending) {
      result[result.pending] = value;
      result.pending = "";
    } else if (value === "--json") result.json = true;
    else if (value === "--fixture") result.backup = DEFAULT_FIXTURE;
    else if (value === "--backup") result.pending = "backup";
    else if (value.startsWith("--backup=")) result.backup = value.slice("--backup=".length);
    else if (value === "--out-dir") result.pending = "outDir";
    else if (value.startsWith("--out-dir=")) result.outDir = value.slice("--out-dir=".length);
    else if (value === "--help" || value === "-h") {
      printHelp();
      process.exit(0);
    } else {
      throw new Error(`Unknown option: ${value}`);
    }
    return result;
  }, { backup: "", outDir: "", json: false, pending: "" });
}

function runDisasterRecoveryDrill(options = {}) {
  const generatedAt = new Date().toISOString();
  const checks = [];
  const backupPath = options.backup ? path.resolve(ROOT, options.backup) : "";
  let backup = null;
  let restoreDir = "";
  let restoredWorkspacePath = "";

  if (!backupPath) {
    checks.push(fail("backup-selected", "Backup selected", "No backup file provided", "Pass --backup <server-backup.json> or use --fixture for a local drill."));
  } else {
    checks.push(pass("backup-selected", "Backup selected", path.relative(ROOT, backupPath)));
  }

  if (backupPath) {
    try {
      backup = JSON.parse(fs.readFileSync(backupPath, "utf8"));
      checks.push(pass("backup-readable", "Backup readable", "Backup file is valid JSON"));
    } catch (error) {
      checks.push(fail("backup-readable", "Backup readable", `Could not parse backup: ${error.message}`, "Create a fresh server backup and rerun the drill."));
    }
  }

  if (backup) {
    const envelope = backup.type === "agora.workspace-backup" && backup.version === 1 && backup.snapshot && backup.workspace?.id && backup.workspace?.name;
    checks.push(gate({
      id: "backup-envelope",
      label: "Backup envelope",
      done: envelope,
      detail: envelope ? `${backup.workspace.name} (${backup.workspace.id})` : "Backup envelope is missing type, version, workspace identity, or snapshot",
      fix: "Use a server backup generated by POST /api/backups/run."
    }));
    checks.push(checkCounts(backup));
  }

  if (backup?.snapshot) {
    try {
      restoreDir = options.outDir ? path.resolve(ROOT, options.outDir) : fs.mkdtempSync(path.join(os.tmpdir(), "agora-recovery-drill-"));
      fs.mkdirSync(restoreDir, { recursive: true });
      restoredWorkspacePath = path.join(restoreDir, "workspace.json");
      fs.writeFileSync(restoredWorkspacePath, `${JSON.stringify({
        metadata: {
          restoredAt: generatedAt,
          source: "disaster-recovery-drill",
          backupGeneratedAt: backup.generatedAt || "",
          backupWorkspaceId: backup.workspace?.id || ""
        },
        snapshot: backup.snapshot
      }, null, 2)}\n`);
      checks.push(pass("restore-write", "Restore write", path.relative(ROOT, restoredWorkspacePath)));
      const restored = JSON.parse(fs.readFileSync(restoredWorkspacePath, "utf8"));
      const sameWorkspace = restored.snapshot?.workspace?.id === backup.workspace?.id;
      checks.push(gate({
        id: "restore-readback",
        label: "Restore readback",
        done: sameWorkspace,
        detail: sameWorkspace ? `Restored workspace ${restored.snapshot.workspace.name || backup.workspace.name}` : "Restored workspace identity did not match backup",
        fix: "Stop and inspect the backup before attempting a production restore."
      }));
      checks.push(checkRestoredCounts(backup, restored.snapshot));
    } catch (error) {
      checks.push(fail("restore-write", "Restore write", `Could not write isolated restore: ${error.message}`, "Check local disk permissions or pass --out-dir to a writable path."));
    }
  }

  const blockers = checks.filter((check) => check.status === "fail");
  return {
    ok: blockers.length === 0,
    generatedAt,
    profile: "disaster-recovery-drill",
    backup: backupPath ? path.relative(ROOT, backupPath) : "",
    restoreDir: restoreDir ? path.relative(ROOT, restoreDir) : "",
    restoredWorkspacePath: restoredWorkspacePath ? path.relative(ROOT, restoredWorkspacePath) : "",
    summary: {
      passing: checks.filter((check) => check.status === "pass").length,
      blockers: blockers.length,
      total: checks.length
    },
    checks
  };
}

function checkCounts(backup) {
  const counts = backup.counts || {};
  const invalid = COUNT_KEYS.filter((key) => !Number.isFinite(counts[key]) || counts[key] < 0);
  return gate({
    id: "backup-counts",
    label: "Backup counts",
    done: invalid.length === 0,
    detail: invalid.length ? `Invalid counts: ${invalid.join(", ")}` : COUNT_KEYS.map((key) => `${key}: ${counts[key]}`).join(", "),
    fix: "Create a fresh server backup so restore evidence includes all expected count fields."
  });
}

function checkRestoredCounts(backup, snapshot = {}) {
  const mismatches = COUNT_KEYS.filter((key) => {
    const restoredCount = Array.isArray(snapshot[key]) ? snapshot[key].length : 0;
    return restoredCount !== backup.counts?.[key];
  });
  return gate({
    id: "restore-counts",
    label: "Restore counts",
    done: mismatches.length === 0,
    detail: mismatches.length ? `Mismatched counts: ${mismatches.join(", ")}` : "Restored snapshot counts match backup evidence",
    fix: "Do not proceed with production restore until the backup counts and restored snapshot counts match."
  });
}

function gate({ id, label, done, detail, fix }) {
  return done ? pass(id, label, detail) : fail(id, label, detail, fix);
}

function pass(id, label, detail) {
  return { id, label, status: "pass", detail };
}

function fail(id, label, detail, fix) {
  return { id, label, status: "fail", detail, fix };
}

function printReport(report) {
  console.log("Agora disaster recovery drill");
  console.log(`Generated: ${report.generatedAt}`);
  console.log(`Result: ${report.ok ? "PASS" : "FAIL"} (${report.summary.passing}/${report.summary.total} passing, ${report.summary.blockers} blockers)`);
  if (report.restoreDir) console.log(`Restore dir: ${report.restoreDir}`);
  console.log("");
  report.checks.forEach((check) => {
    const marker = check.status === "pass" ? "PASS" : "FAIL";
    console.log(`[${marker}] ${check.label}`);
    console.log(`  ${check.detail}`);
    if (check.status !== "pass") console.log(`  Fix: ${check.fix}`);
  });
}

function printHelp() {
  console.log(`Agora disaster recovery drill

Usage:
  npm run drill:recovery -- --backup <server-backup.json>
  npm run agora -- recovery-drill --backup <server-backup.json>

Options:
  --backup <file>  Server backup generated by POST /api/backups/run
  --fixture        Use the repository backup fixture for local validation
  --out-dir <dir>  Write the isolated restored workspace to a specific directory
  --json           Print machine-readable JSON
`);
}

module.exports = { runDisasterRecoveryDrill };
